"""Render knowledge/lab_manual.md to data/datasheets/LabLens_Lab_Manual.pdf (one "## " section per page)
and (re)build the retrieval index over every PDF in data/datasheets.

    python scripts/build_manual.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def parse_sections(md: str):
    title = re.search(r"^# (.+)$", md, re.M).group(1).strip()
    parts = re.split(r"^## ", md, flags=re.M)[1:]
    out = []
    for p in parts:
        head, _, body = p.partition("\n")
        paras = [re.sub(r"\s*\n\s*", " ", x).strip() for x in re.split(r"\n\s*\n", body) if x.strip()]
        out.append((head.strip(), paras))
    return title, out


def render_pdf(md_path: Path, pdf_path: Path) -> int:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer

    title, sections = parse_sections(md_path.read_text(encoding="utf-8"))
    styles = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=10.5, leading=14.5, spaceAfter=6)
    h = ParagraphStyle("h", parent=styles["Heading1"], fontSize=17, spaceAfter=10)

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8.5)
        canvas.drawString(18 * mm, 10 * mm, f"{title}  -  generated by LabLens  -  verify values against the "
                                             "manufacturer datasheet")
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"page {doc.page}")
        canvas.restoreState()

    story = []
    for i, (head, paras) in enumerate(sections):
        story.append(Paragraph(head, h))
        for p in paras:
            story.append(Paragraph(p.replace("&", "&amp;").replace("<", "&lt;"), body))
        story.append(Spacer(1, 4))
        if i < len(sections) - 1:
            story.append(PageBreak())
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    SimpleDocTemplate(str(pdf_path), pagesize=A4, title=title, leftMargin=18 * mm, rightMargin=18 * mm,
                      topMargin=18 * mm, bottomMargin=18 * mm).build(story, onFirstPage=footer, onLaterPages=footer)
    return len(sections)


def main() -> None:
    from lablens.config import get_config
    from lablens.rag.store import build_store

    cfg = get_config()
    pdf_dir = cfg.path("rag.pdf_dir", "data/datasheets")
    n = render_pdf(ROOT / "knowledge" / "lab_manual.md", pdf_dir / "LabLens_Lab_Manual.pdf")
    print(f"manual: {n} pages -> {pdf_dir / 'LabLens_Lab_Manual.pdf'}")
    store = build_store(cfg)
    store.reset()
    added = store.build_from_dir(pdf_dir)
    print(f"index: {added} chunks from {len(store.sources())} PDFs (dense embeddings: {store.use_dense})")


if __name__ == "__main__":
    main()
